-- LogWarden schema. Written to run on both PostgreSQL (production) and H2 in PostgreSQL mode (local and tests).

CREATE TABLE events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_time  TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    source      VARCHAR(20)  NOT NULL,
    host        VARCHAR(255),
    event_type  VARCHAR(30)  NOT NULL,
    user_name   VARCHAR(255),
    src_ip      VARCHAR(64),
    dst_port    INTEGER,
    target      VARCHAR(1000),
    status      INTEGER,
    message     VARCHAR(1000),
    raw         VARCHAR(8000)
);
CREATE INDEX events_time ON events (event_time);
CREATE INDEX events_ip ON events (src_ip);
CREATE INDEX events_user ON events (user_name);
CREATE INDEX events_type ON events (event_type);

CREATE TABLE alerts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id     VARCHAR(60)  NOT NULL,
    title       VARCHAR(300) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    severity    VARCHAR(10)  NOT NULL,
    mitre       VARCHAR(20),
    entity      VARCHAR(300) NOT NULL,
    first_seen  TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen   TIMESTAMP WITH TIME ZONE NOT NULL,
    hit_count   INTEGER NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    assignee    VARCHAR(100),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX alerts_rule_entity ON alerts (rule_id, entity);
CREATE INDEX alerts_status ON alerts (status);
CREATE INDEX alerts_last_seen ON alerts (last_seen);

-- Which events are the evidence for an alert
CREATE TABLE alert_events (
    alert_id BIGINT NOT NULL REFERENCES alerts (id) ON DELETE CASCADE,
    event_id BIGINT NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    PRIMARY KEY (alert_id, event_id)
);
CREATE INDEX alert_events_event ON alert_events (event_id);

-- The investigation trail: analysts' notes and every status change
CREATE TABLE alert_notes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id   BIGINT NOT NULL REFERENCES alerts (id) ON DELETE CASCADE,
    author     VARCHAR(100) NOT NULL,
    body       VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX alert_notes_alert ON alert_notes (alert_id);

CREATE TABLE rule_settings (
    rule_id VARCHAR(60) PRIMARY KEY,
    enabled BOOLEAN NOT NULL
);
